"""Build monthly drift reports from the prediction log written by scripts/replay.py.

Reference: the validation period (Jul to Sep 2016) with the model's scores and
labels, stored in the model artifact.

Usage: python scripts/monitor.py [--db data/replay.db]
Writes: reports/drift/<YYYY-MM>.md, reports/drift/figures/*.png,
        reports/drift/README.md, reports/monitoring_summary.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from hotelmon import artifacts, config, monitoring  # noqa: E402
from hotelmon.logdb import PredictionLog  # noqa: E402

OUT = config.REPORTS_DIR / "drift"
FIG = OUT / "figures"


def fmt_p(p: float) -> str:
    return "<1e-300" if p == 0 else f"{p:.1e}" if p < 1e-3 else f"{p:.3f}"


def period_markdown(period: str, s: dict, ref_perf: dict, version: str) -> str:
    perf, sd = s["performance"], s["score_drift"]
    t = s["feature_drift"].sort_values("psi", ascending=False)
    lines = [
        f"# Drift report: {period}",
        "",
        f"Model `{version}`. Reference: validation period, Jul to Sep 2016 "
        f"({ref_perf['n_labeled']} bookings). This period: {s['n']} bookings.",
        "",
        "Generated by `scripts/monitor.py`.",
        "",
        "## Performance (labels arrived)",
        "",
        "| Metric | Reference | This period |",
        "|---|---|---|",
        f"| ROC AUC | {ref_perf['roc_auc']:.3f} | {perf['roc_auc']:.3f} "
        f"(95% CI {perf['roc_auc_ci95'][0]:.3f} to {perf['roc_auc_ci95'][1]:.3f}) |",
        f"| PR AUC | {ref_perf['pr_auc']:.3f} | {perf['pr_auc']:.3f} |",
        f"| Brier | {ref_perf['brier']:.3f} | {perf['brier']:.3f} |",
        f"| Cancellation rate | {ref_perf['positive_rate']:.3f} | {perf['positive_rate']:.3f} |",
        "",
        "## Prediction drift",
        "",
        f"Score PSI {sd['psi']:.3f} ({sd['psi_flag']}). KS statistic {sd['ks_statistic']:.3f}, "
        f"p {fmt_p(sd['ks_p_value'])}. Mean score {sd['mean_ref']:.3f} in the reference, "
        f"{sd['mean_cur']:.3f} now.",
        "",
        "## Feature drift",
        "",
        f"{s['n_features_psi_moderate_or_more']} of {len(t)} features have PSI >= 0.1. "
        f"{s['n_features_test_flagged']} of {len(t)} fail the KS or chi-square test "
        "at 0.05 with a Bonferroni correction.",
        "",
        "| Feature | Type | PSI | PSI flag | Test | Statistic | p-value | Test flag |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in t.itertuples():
        lines.append(
            f"| {r.feature} | {r.kind} | {r.psi:.3f} | {r.psi_flag} | {r.test} | "
            f"{r.statistic:.3f} | {fmt_p(r.p_value)} | {'yes' if r.test_flag else 'no'} |"
        )
    lines += ["", f"![Score and top drifted features](figures/{period}.png)", ""]
    return "\n".join(lines)


def period_figure(period: str, ref: pd.DataFrame, cur: pd.DataFrame, table: pd.DataFrame):
    top = table.sort_values("psi", ascending=False).head(2)
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6))
    bins = np.linspace(0, 1, 21)
    axes[0].hist(ref["score"], bins=bins, density=True, alpha=0.5, label="reference")
    axes[0].hist(cur["score"], bins=bins, density=True, alpha=0.5, label=period)
    axes[0].set_title("Score distribution")
    axes[0].legend()
    for ax, row in zip(axes[1:], top.itertuples(), strict=False):
        f = row.feature
        if row.kind == "numeric":
            hi = np.quantile(np.concatenate([ref[f], cur[f]]), 0.99)
            b = np.linspace(0, max(hi, 1), 30)
            ax.hist(ref[f].clip(upper=hi), bins=b, density=True, alpha=0.5, label="reference")
            ax.hist(cur[f].clip(upper=hi), bins=b, density=True, alpha=0.5, label=period)
        else:
            rp = ref[f].value_counts(normalize=True)
            cp = cur[f].value_counts(normalize=True)
            cats = (rp.add(cp, fill_value=0)).sort_values(ascending=False).index[:8]
            x = np.arange(len(cats))
            ax.bar(x - 0.2, rp.reindex(cats, fill_value=0), 0.4, label="reference")
            ax.bar(x + 0.2, cp.reindex(cats, fill_value=0), 0.4, label=period)
            ax.set_xticks(x, [str(c)[:10] for c in cats], rotation=45, ha="right", fontsize=8)
        ax.set_title(f"{f} (PSI {row.psi:.2f})")
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / f"{period}.png", dpi=100)
    plt.close(fig)


def summary_figures(periods: list[str], summaries: dict, ref_perf: dict):
    psi = pd.DataFrame(
        {p: summaries[p]["feature_drift"].set_index("feature")["psi"] for p in periods}
    )
    psi.loc["model score"] = [summaries[p]["score_drift"]["psi"] for p in periods]
    fig, ax = plt.subplots(figsize=(10, 7))
    im = ax.imshow(psi.to_numpy(), aspect="auto", cmap="Reds", vmin=0, vmax=0.5)
    ax.set_xticks(range(len(periods)), periods, rotation=45, ha="right")
    ax.set_yticks(range(len(psi)), psi.index)
    for i in range(psi.shape[0]):
        for j in range(psi.shape[1]):
            ax.text(j, i, f"{psi.iat[i, j]:.2f}", ha="center", va="center", fontsize=6)
    fig.colorbar(im, ax=ax, label="PSI vs reference (clipped at 0.5)")
    ax.set_title("PSI per feature and month")
    fig.tight_layout()
    fig.savefig(FIG / "psi_heatmap.png", dpi=110)
    plt.close(fig)

    auc = [summaries[p]["performance"]["roc_auc"] for p in periods]
    lo = [summaries[p]["performance"]["roc_auc_ci95"][0] for p in periods]
    hi = [summaries[p]["performance"]["roc_auc_ci95"][1] for p in periods]
    fig, ax = plt.subplots(figsize=(9, 3.8))
    x = np.arange(len(periods))
    ax.fill_between(x, lo, hi, alpha=0.2, label="95% bootstrap CI")
    ax.plot(x, auc, marker="o", label="ROC AUC (production month)")
    ax.axhline(ref_perf["roc_auc"], color="grey", ls="--", label="validation ROC AUC")
    ax2 = ax.twinx()
    ax2.plot(
        x,
        [summaries[p]["score_drift"]["psi"] for p in periods],
        color="C3",
        marker="s",
        ls=":",
        label="score PSI",
    )
    ax2.set_ylabel("score PSI")
    ax.set_xticks(x, periods, rotation=45, ha="right")
    ax.set_ylabel("ROC AUC")
    ax.set_title("Performance and prediction drift by arrival month")
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(FIG / "auc_over_time.png", dpi=110)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", type=Path, default=config.DATA_DIR / "replay.db")
    args = ap.parse_args()
    FIG.mkdir(parents=True, exist_ok=True)

    art = artifacts.load(artifacts.resolve(), with_reference=True)
    ref = monitoring.reference_view(art.reference)
    ref_perf = monitoring.performance(ref["label"], ref["score"])

    log = PredictionLog(args.db)
    cur_all = monitoring.log_view(log.read())
    log.close()
    cur_all["period"] = cur_all["arrival_date"].dt.strftime("%Y-%m")
    periods = sorted(cur_all["period"].unique())

    summaries, rows = {}, []
    for period in periods:
        cur = cur_all[cur_all["period"] == period]
        s = monitoring.window_summary(ref, cur)
        summaries[period] = s
        (OUT / f"{period}.md").write_text(period_markdown(period, s, ref_perf, art.version))
        period_figure(period, ref, cur, s["feature_drift"])
        perf = s["performance"]
        rows.append(
            {
                "period": period,
                "n": s["n"],
                "positive_rate": perf["positive_rate"],
                "roc_auc": perf["roc_auc"],
                "roc_auc_ci95": perf["roc_auc_ci95"],
                "pr_auc": perf["pr_auc"],
                "brier": perf["brier"],
                "auc_drop_vs_valid": ref_perf["roc_auc"] - perf["roc_auc"],
                "score_psi": s["score_drift"]["psi"],
                "score_ks": s["score_drift"]["ks_statistic"],
                "mean_score": s["score_drift"]["mean_cur"],
                "mean_feature_psi": s["mean_feature_psi"],
                "max_feature_psi": s["max_feature_psi"],
                "max_psi_feature": s["feature_drift"]
                .sort_values("psi", ascending=False)
                .iloc[0]["feature"],
                "n_features_psi_ge_0.1": s["n_features_psi_moderate_or_more"],
                "n_features_test_flagged": s["n_features_test_flagged"],
                "n_features": len(s["feature_drift"]),
            }
        )
    summary_figures(periods, summaries, ref_perf)

    result = {
        "model_version": art.version,
        "reference": {"period": "2016-07 to 2016-09"} | ref_perf,
        "drift_features": monitoring.DRIFT_FEATURES,
        "excluded_from_drift": ["arrival_month"],
        "periods": rows,
    }
    (config.REPORTS_DIR / "monitoring_summary.json").write_text(json.dumps(result, indent=2) + "\n")

    idx = [
        "# Drift reports",
        "",
        "One report per production month, built by `scripts/monitor.py` from the prediction "
        "log that `scripts/replay.py` writes.",
        "",
        "![PSI heatmap](figures/psi_heatmap.png)",
        "",
        "![AUC over time](figures/auc_over_time.png)",
        "",
        "| Month | Bookings | ROC AUC | Score PSI | Features with PSI >= 0.1 | "
        "Features failing test | Report |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        idx.append(
            f"| {r['period']} | {r['n']} | {r['roc_auc']:.3f} | {r['score_psi']:.3f} | "
            f"{r['n_features_psi_ge_0.1']} / {r['n_features']} | "
            f"{r['n_features_test_flagged']} / {r['n_features']} | "
            f"[{r['period']}]({r['period']}.md) |"
        )
    (OUT / "README.md").write_text("\n".join(idx) + "\n")
    print(pd.DataFrame(rows).drop(columns=["roc_auc_ci95"]).round(3).to_string(index=False))


if __name__ == "__main__":
    main()
